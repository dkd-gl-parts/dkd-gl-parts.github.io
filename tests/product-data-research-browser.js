const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.argv[2] || 'playwright');
const root = path.resolve(__dirname,'..');
const out = path.resolve(process.argv[3] || path.join(root,'.qa/product-research'));
fs.mkdirSync(out,{recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  const page = await browser.newPage();
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.setContent('<!doctype html><html lang="ja"><head><meta charset="utf-8"></head><body><select id="manufacturing-cost-category"><option value="">すべて</option><option value="starter">スタータ</option><option value="alternator">オルタネータ</option></select><main>製造原価・検証用の架空データ</main></body></html>');
  await page.addStyleTag({path:path.join(root,'product-data-research.css')});
  await page.evaluate(() => {
    window.qa = {canEdit:true,existing:[],catalog:[],failSearch:false,failMutation:false,failFetch:false,writes:0,resolved:[],registered:null};
    window.canEdit=()=>qa.canEdit;
    window.tCat=v=>v;
    window.fetchCoreProductMasterMatches=async()=>qa.failSearch?{error:{message:'検索通信エラー'}}:{data:qa.existing};
    window.sb={
      from: table => {
        const query = {select:()=>query,or:()=>query,order:()=>query,limit:()=>Promise.resolve({data:qa.catalog}),eq:()=>query,
          single:()=>Promise.resolve(qa.failFetch?{error:{message:'再照合通信エラー'}}:{data:qa.registered || qa.existing[0]})};
        return query;
      },
      rpc:async(name,args)=>{
        if(name!=='register_researched_product') throw new Error('unexpected stock or financial mutation');
        qa.writes++;
        qa.registered={...args.p_product,dkd_shohin_id:42};
        qa.existing=[qa.registered];
        return qa.failMutation?{error:{message:'登録応答不明'}}:{data:42};
      }
    };
    window.qaOpen=token=>DcatsProductResearch.open({token,category:'',onResolved:async p=>{qa.resolved.push(p.dkd_shohin_id);}});
  });
  await page.addScriptTag({path:path.join(root,'product-data-research.js')});
  await page.setViewportSize({width:1366,height:900});
  await page.evaluate(()=>qaOpen('31100-TEST-001'));
  await page.waitForSelector('#product-data-research[open]');
  assert(await page.locator('#pdr-save').isDisabled());
  assert.equal(await page.locator('#pdr-genuine').inputValue(),'','do not guess the imported number type');
  await page.screenshot({path:path.join(out,'desktop-unresolved.png')});
  await page.evaluate(()=>qa.catalog=[{id:10,source_name:'検証用カタログ',source_record_key:'p.10',genuine_part_number:'31100-TEST-001',manufacturer_part_number:'',catalog_manufacturer:''}]);
  await page.locator('[data-pdr-search]').click();
  await page.locator('[data-pdr-catalog]').click();
  assert(await page.locator('#pdr-save').isDisabled());
  assert.match(await page.locator('#pdr-gate').textContent(),/カテゴリ.*メーカー/);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(out,'mobile-incomplete-catalog.png')});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile document must not overflow');
  const fill=async()=>{
    await page.locator('#pdr-category').selectOption('starter');
    await page.locator('#pdr-manufacturer').fill('DENSO');
    await page.locator('#pdr-genuine').fill('31100-TEST-001');
    await page.locator('#pdr-mfr-part').fill('228000-TEST1');
    await page.locator('#pdr-source-type').selectOption('document');
    await page.locator('#pdr-source-reference').fill('検証用の原票 p.1、現物ラベルを確認');
    await page.locator('#pdr-confirmed').check();
  };
  await fill(); assert(await page.locator('#pdr-save').isEnabled());
  await page.locator('#pdr-manufacturer').fill('DENSO確認');
  assert(!(await page.locator('#pdr-confirmed').isChecked()),'editing identity resets confirmation');
  await fill();
  await page.screenshot({path:path.join(out,'mobile-ready.png')});
  await page.locator('#pdr-save').click();
  await page.waitForSelector('#product-data-research:not([open])',{state:'attached'});
  assert.equal(await page.evaluate(()=>qa.writes),1);
  assert.equal(await page.evaluate(()=>qa.resolved.length),1);
  await page.evaluate(()=>qaOpen('31100-TEST-001'));
  assert(await page.locator('#pdr-save').isDisabled(),'existing master prohibits new registration');
  await page.locator('[data-pdr-existing]').click();
  await page.waitForSelector('#product-data-research:not([open])',{state:'attached'});
  await page.evaluate(()=>{qa.existing=[];qa.failSearch=true;});
  await page.evaluate(()=>qaOpen('31100-TEST-001'));
  assert(await page.locator('#pdr-save').isDisabled());
  assert.match(await page.locator('#pdr-search-status').textContent(),/調査できません/);
  await page.setViewportSize({width:1366,height:900});
  await page.screenshot({path:path.join(out,'desktop-search-error.png')});
  await page.locator('[data-pdr-close]').first().click();
  await page.evaluate(()=>{qa.failSearch=false;qa.canEdit=false;});
  await page.evaluate(()=>qaOpen('31100-TEST-001'));
  await fill(); assert(await page.locator('#pdr-save').isDisabled(),'readonly cannot register');
  await page.locator('[data-pdr-close]').first().click();
  await page.evaluate(()=>{qa.canEdit=true;qa.failMutation=true;});
  await page.evaluate(()=>qaOpen('31100-TEST-001'));
  await fill();
  assert(await page.locator('#pdr-save').isEnabled(),await page.locator('#pdr-gate').textContent());
  await page.locator('#pdr-save').click();
  await page.waitForFunction(()=>document.getElementById('pdr-save-status').textContent.includes('再登録できません'));
  assert(await page.locator('#pdr-save').isDisabled(),'uncertain response must block a repeated insert');
  await page.locator('[data-pdr-search]').click();
  await page.locator('[data-pdr-existing]').click();
  await page.waitForSelector('#product-data-research:not([open])',{state:'attached'});
  await page.evaluate(()=>{qa.existing=[];qa.failMutation=false;qa.failFetch=true;});
  await page.evaluate(()=>qaOpen('31100-TEST-001'));
  await fill();
  assert(await page.locator('#pdr-save').isEnabled(),await page.locator('#pdr-gate').textContent());
  await page.locator('#pdr-save').click();
  await page.waitForFunction(()=>document.getElementById('pdr-save-status').textContent.includes('再照合未完了'));
  assert(await page.locator('#pdr-save').isDisabled());
  assert(await page.locator('#pdr-registered').isVisible());
  const before=await page.evaluate(()=>qa.writes);
  await page.evaluate(()=>qa.failFetch=false);
  await page.locator('#pdr-registered').click();
  await page.waitForSelector('#product-data-research:not([open])',{state:'attached'});
  assert.equal(await page.evaluate(()=>qa.writes),before,'rematch must not re-register');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Desktop 1366x900 / mobile 390x844: loading, incomplete catalog, confirmed success, duplicate, permission, network-error and recovery flows passed.');
})().catch(error=>{console.error(error);process.exit(1);});
