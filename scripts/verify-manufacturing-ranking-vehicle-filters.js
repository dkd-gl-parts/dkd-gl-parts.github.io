const fs=require('fs');
const path=require('path');
const vm=require('vm');
const assert=require('assert/strict');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'manufacturing-ranking-report.js'),'utf8');
const context={window:{},document:{getElementById(){return null;},querySelectorAll(){return []; }},console,Intl,Date,encodeURIComponent,setTimeout};
vm.runInNewContext(source,context);
const api=context.window.DCatsManufacturingRankingReport;
const options={categories:['商品別出荷実績集計'],productCategory:'all',metric:'shipment',rankScope:'overall',startRank:1,endRank:100,minShipment:0,query:'',compatibilityMode:'all',compatibilityBasis:'part_number',showCoreStock:false,showMissingMaster:false,showVehicleClassification:true,vehicleWork:'all',vehicleKei:'all',vehicleCommon:'all'};
const profile=(work,kei,common='他の適合先は未判定',unknown=true)=>({version:'business-kei-20261009',work_tags:work,kei_kinds:kei,kei_common:common,other_fitment_unknown:unknown});
function row(code,maker,n,p){return api.mapDatabaseRow({id:code,dataset_id:'synthetic',category_name:'商品別出荷実績集計',is_aggregate:true,product_name:'オルタネータ',product_code:code,genuine_part_number:'G'+code,manufacturer_part_number:maker,shipment_count:n,substitute_count:0,vehicle_classification:p});}
const rows=[row('1','MAKER1',100,profile(['トラック'],[],'未確認',false)),row('2','MAKER2',80,profile(['軽トラック'],['軽トラック'],'確認資料では軽四のみ',false)),row('3','MAKER3',60,profile([],['軽乗用車'],'軽四以外にも適合',true)),row('4','MAKER4',50,null),row('5','prefix-ａｌｄｋ-suffix',999,profile(['バス'],[],'未確認',false)),row('6','MAKER6',40,profile(['営業車・商用バン'],[],'未確認',false))];
const rank=extra=>api.buildRanking(rows,{...options,...extra});
assert.equal(rank({}).results.length,5);
assert.equal(rank({}).excludedDksRowCount,1);
assert.equal(rank({vehicleWork:'confirmed'}).results.length,3);
assert.equal(rank({vehicleWork:'business_or_kei'}).results.length,4);
assert.equal(rank({vehicleKei:'confirmed'}).results.length,2);
assert.equal(rank({vehicleKei:'軽乗用車'}).results[0].row.productCode,'3');
assert.equal(rank({vehicleWork:'軽トラック',vehicleKei:'confirmed'}).results.length,1);
assert.equal(rank({vehicleWork:'トラック',vehicleKei:'confirmed'}).results.length,0);
assert.equal(rank({vehicleCommon:'軽四以外にも適合'}).results[0].row.productCode,'3');
assert.equal(rank({vehicleCommon:'other_unknown'}).results.length,1);
assert.equal(rank({vehicleKei:'unconfirmed'}).results.length,3,'unconfirmed is not a non-kei assertion');
assert.equal(rank({vehicleKei:'confirmed',startRank:2,endRank:2}).results[0].row.productCode,'3');
assert.equal(rank({vehicleKei:'confirmed'}).results[0].rank,1,'filter before rank');
const compatible=[row('20','SAME',10,profile(['トラック'],[],'未確認',false)),row('21','SAME',100,null)];
const consolidated=api.buildRanking(compatible,{...options,vehicleWork:'トラック',compatibilityMode:'consolidated'});
assert.equal(consolidated.results[0].shipment,10,'unmatched compatibility member quantity excluded');
const wrong=structuredClone(rows[0]);wrong.vehicleClassification.version='unknown';
assert.equal(api.matchesVehicleFilters(wrong,{vehicleWork:'confirmed'}),false);
const genuineOnly=row('9','MAKER9',1,null);genuineOnly.genuine='ALDK123';
assert.equal(api.buildRanking([genuineOnly],options).results.length,1,'exclude only manufacturer ALDK');
const category={...rows[2],id:'category3',sheet:'オルタ',isAggregate:false};
assert.equal(api.buildRanking([...rows,category],{...options,productCategory:'オルタ',vehicleKei:'confirmed'}).results.length,1);
const result=rank({vehicleKei:'confirmed'}).results;
const csv=api.buildExcelRows(result,options);
assert.equal(csv[0].slice(-3).join(','),'業務用途の適合,軽四適合,軽四の共用区分');
assert.equal(csv[1].length,csv[0].length);
assert(csv[1].includes('確認資料では軽四のみ'));
const supplierCsv=api.buildExcelRows(result,{...options,reportType:'supplier_availability',supplierId:'all',supplierStatus:'all'});
assert.equal(supplierCsv[0].slice(-3).join(','),'業務用途の適合,軽四適合,軽四の共用区分');
assert.equal(supplierCsv[1].length,supplierCsv[0].length);
const printed=api.buildPrintHtml(result,{...options,vehicleKei:'confirmed',orientation:'portrait'});
assert(printed.includes('ALDK除外')&&printed.includes('軽四: 適合あり')&&printed.includes('軽四以外にも適合'));
assert(api.printFileTitle(options.categories,1,100,new Date(),'manufacturing','all',{...options,vehicleKei:'confirmed'}).includes('軽四'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const id of ['vehicle-work','vehicle-kei','vehicle-common','show-vehicle'])assert(html.includes('id="manufacturing-ranking-'+id+'"'));
assert(!source.includes('vehicle-classification-2025-20261009.json'),'private classification data stays outside public assets');
console.log('manufacturing vehicle filters: ALDK, business/kei/common, unknowns, category intersection, rank, compatibility, CSV/PDF passed');
